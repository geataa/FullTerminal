static const wchar_t* const* const kAllTables[16] = {
    kEn, kTr, kRu, kUk, kDe, kFr, kEs, kIt,
    kPt, kNl, kPl, kZh, kJa, kKo, kAr, kHi
};

static LangId       s_currentLang = LangId::En; // Varsayilan secili dil: Ingilizce
static std::wstring s_currentCode = L"en";

void I18n::Init(const std::wstring& langCode) {
    SetLanguage(langCode);
}

void I18n::SetLanguage(LangId id) {
    int idx = static_cast<int>(id);
    if (idx < 0 || idx >= (int)kLanguages.size()) {
        idx = 0; // Fallback to English
    }
    s_currentLang = static_cast<LangId>(idx);
    s_currentCode = kLanguages[idx].code;
}

void I18n::SetLanguage(const std::wstring& code) {
    std::wstring lower = code;
    for (auto& c : lower) c = (wchar_t)towlower(c);
    if (lower.empty()) {
        SetLanguage(LangId::En);
        return;
    }
    for (size_t i = 0; i < kLanguages.size(); ++i) {
        if (lower == kLanguages[i].code) {
            SetLanguage(static_cast<LangId>(i));
            return;
        }
    }
    // Eger bulunamazsa varsayilan Ingilizce
    SetLanguage(LangId::En);
}

LangId I18n::CurrentLang() {
    return s_currentLang;
}

const wchar_t* I18n::CurrentCode() {
    int idx = static_cast<int>(s_currentLang);
    if (idx < 0 || idx >= (int)kLanguages.size()) idx = 0;
    return kLanguages[idx].code;
}

const wchar_t* I18n::CurrentName() {
    int idx = static_cast<int>(s_currentLang);
    if (idx < 0 || idx >= (int)kLanguages.size()) idx = 0;
    return kLanguages[idx].name;
}

const wchar_t* I18n::CurrentBadge() {
    int idx = static_cast<int>(s_currentLang);
    if (idx < 0 || idx >= (int)kLanguages.size()) idx = 0;
    return kLanguages[idx].badge;
}

const wchar_t* I18n::Get(Msg key) {
    const int ki = static_cast<int>(key);
    if (ki < 0 || ki >= static_cast<int>(Msg::_Count)) return L"";
    const int li = static_cast<int>(s_currentLang);
    if (li < 0 || li >= 16) {
        return kEn[ki];
    }
    const wchar_t* str = kAllTables[li][ki];
    if (!str || !str[0]) {
        return kEn[ki]; // Fallback to English
    }
    return str;
}

const std::vector<LangInfo>& I18n::Languages() {
    return kLanguages;
}

void I18n::CycleLanguage() {
    int next = (static_cast<int>(s_currentLang) + 1) % (int)kLanguages.size();
    SetLanguage(static_cast<LangId>(next));
}

