template <size_t N>
bool InRanges(char32_t cp, const Range (&tbl)[N]) {
    size_t lo = 0, hi = N;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (cp < tbl[mid].lo)      hi = mid;
        else if (cp > tbl[mid].hi) lo = mid + 1;
        else                       return true;
    }
    return false;
}

