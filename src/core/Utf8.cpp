int CharWidth(char32_t cp) {
    if (cp == 0) return 0;
    if (cp < 0x20 || (cp >= 0x7F && cp < 0xA0)) return 0; // kontrol
    if (cp < 0x300) return 1;                             // hizli yol: Latin
    if (InRanges(cp, kZeroWidth)) return 0;
    if (InRanges(cp, kWide)) return 2;
    return 1;
}

